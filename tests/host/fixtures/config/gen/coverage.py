#!/usr/bin/env python3
"""Writes ../COVERAGE.txt: every release tag and the fixture directory whose
config writer is the same (src/config.cpp, src/config.h and src/utils.h byte
for byte). An UNCOVERED line means a tag needs its own fixtures (add it to
regen.sh). Run from anywhere inside the repo."""
import hashlib, os, subprocess

GEN = os.path.dirname(os.path.abspath(__file__))
FIX = os.path.dirname(GEN)


def git(*args):
    r = subprocess.run(["git", "-C", GEN, *args], capture_output=True, text=True)
    return r.returncode, r.stdout


def writer_key(tag):
    parts = []
    for f in ("src/config.cpp", "src/config.h", "src/utils.h"):
        rc, text = git("show", f"{tag}:{f}")
        if f == "src/config.cpp" and rc:
            return None
        parts.append(text)
    return hashlib.sha1("\0".join(parts).encode()).hexdigest()[:8]


reps = sorted(d for d in os.listdir(FIX) if d.startswith("v"))
by_key = {writer_key(r): r for r in reps}
lines = ["# Every release tag -> the fixture directory covering its config writer",
         "# (identical src/config.cpp, config.h, utils.h). Generated by gen/coverage.py."]
for tag in git("tag", "-l", "v*", "--sort=creatordate")[1].split():
    k = writer_key(tag)
    cover = "no config (no src/config.cpp)" if k is None else by_key.get(k, "UNCOVERED " + k)
    lines.append(f"{tag:30s} {cover}")
open(os.path.join(FIX, "COVERAGE.txt"), "w").write("\n".join(lines) + "\n")
print("\n".join(l for l in lines if "UNCOVERED" in l) or "all tags covered")
